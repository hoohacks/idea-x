/**
 * Generates the transitional ruleset used while scores are being moved out from
 * under /teams.
 *
 * Moving scores is not a change you can deploy in one step, because the rules
 * and the client are coupled: the write path itself moves, so there is no
 * ordering in which old-client/new-rules and new-client/old-rules both work.
 * The cutover therefore runs through an intermediate ruleset that permits BOTH
 * locations at once, so the live app keeps working while the new build ships
 * and the migration runs.
 *
 * This is generated rather than committed so it cannot drift from
 * database.rules.json. Run it, paste the output into the console, and delete it
 * when the cutover is done.
 *
 *   node scripts/make-cutover-rules.mjs            union rules: both locations live
 *   node scripts/make-cutover-rules.mjs --freeze   union rules, legacy path read-only
 *
 * `--freeze` is what you publish immediately before running migrate-scores.mjs.
 * Without it, a judge who submits between the migration's read and its write has
 * their card read-missed and then nulled -- silently lost.
 *
 * See "Moving scores off the team node" in docs/migrations.md for the full sequence.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..");

const OUT = join(repoRoot, "database.rules.cutover.json");

// The console accepts // comments but JSON.parse does not. Same stripper as
// src/schema.test.js -- keep the two in step.
function stripComments(source) {
  return source.replace(/^\s*\/\/.*$/gm, "");
}

function legacyScoreBlock(scoreLeafRules, frozen) {
  // The legacy per-judge block, rebuilt from the new one so the validation can
  // never disagree between the two locations during the window both are live.
  // Two fields differ by necessity: the old records have no `enteredBy`, and
  // the old path keyed the judge as $judgeId.
  const leaf = structuredClone(scoreLeafRules);

  leaf[".validate"] = leaf[".validate"].replace(",'enteredBy'", "");
  delete leaf.enteredBy;
  delete leaf.source;
  leaf.judgeUid[".validate"] = "newData.val() === $judgeId";

  leaf[".read"] = "auth != null && auth.uid === $judgeId";
  leaf[".write"] = frozen
    ? // Frozen for the migration. Admins still write through the root rule,
      // which is what lets migrate-scores.mjs null these nodes out.
      "false"
    : "auth != null && auth.uid === $judgeId && root.child('judges').child(auth.uid).exists()";

  return { $judgeId: leaf };
}

const frozen = process.argv.includes("--freeze");

const source = readFileSync(join(repoRoot, "database.rules.json"), "utf8");
const rules = JSON.parse(stripComments(source)).rules;

const scoreLeaf = rules.scores.$round.$teamId.$judgeUid;

// 1. Both score locations live at once.
rules.teams.$teamId.scores = legacyScoreBlock(scoreLeaf, frozen);
rules.teams.$teamId.finalScores = legacyScoreBlock(scoreLeaf, frozen);

// 2. The deployed app still does onValue('/finalRound'), which needs a read at
//    the node itself. This is the leak the split closes, so it is restored here
//    only for the length of the cutover.
rules.finalRound[".read"] = "auth != null";

const banner = [
  "// GENERATED by scripts/make-cutover-rules.mjs -- do not edit.",
  "//",
  "// TRANSITIONAL RULES. Both score locations are writable and /finalRound is",
  "// still world-readable to signed-in users. Publish database.rules.json and",
  "// delete this file as soon as the migration is verified.",
  frozen
    ? "// FROZEN: the legacy score path is read-only. Publish this immediately\n// before running migrate-scores.mjs."
    : "// NOT FROZEN: re-run with --freeze before running migrate-scores.mjs.",
  "",
].join("\n");

writeFileSync(OUT, `${banner}${JSON.stringify({ rules }, null, 2)}\n`);

console.log(`Wrote ${OUT}`);
console.log(frozen ? "Legacy score path is FROZEN (read-only)." : "Both score paths are writable.");
console.log("Paste it into Firebase console -> Realtime Database -> Rules.");
